// Writes app/sw.js: the offline cache list, stamped with a fingerprint of every app file.
// Run it before each upload:  node tools/build-sw.mjs
// A changed fingerprint is what tells an installed copy on the iPad to fetch the update.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'app');
const skip = f => f === 'sw.js' || /(^|\/)\./.test(f) || f.endsWith('.map') || /(^|\/)LICENSE/.test(f) || f.endsWith('.svg') || f.endsWith('.md');

function walk(dir, out = []) {
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full, out);
    else out.push(path.relative(appDir, full).split(path.sep).join('/'));
  }
  return out;
}

const files = walk(appDir).filter(f => !skip(f));
const hash = crypto.createHash('sha256');
for (const f of files) { hash.update(f); hash.update(fs.readFileSync(path.join(appDir, f))); }
const version = hash.digest('hex').slice(0, 12);
const list = ['./', ...files.map(f => `./${f}`)];

const sw = `// Generated by tools/build-sw.mjs. Do not edit by hand.
const VERSION = '${version}';
const CACHE = 'redline-' + VERSION;
const FILES = ${JSON.stringify(list, null, 2)};

// Install: fetch every app file once, so the app opens with no signal.
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});

// Activate: drop the previous version's files.
self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k.startsWith('redline-') && k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Serve app files from the cache; anything not cached goes to the network.
self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = (await cache.match(req, { ignoreSearch: true })) || (req.mode === 'navigate' ? await cache.match('./index.html') : null);
    if (hit) return hit;
    const res = await fetch(req);
    if (res.ok) cache.put(req, res.clone());
    return res;
  })());
});
`;
fs.writeFileSync(path.join(appDir, 'sw.js'), sw);
const bytes = files.reduce((n, f) => n + fs.statSync(path.join(appDir, f)).size, 0);
console.log(`sw.js written: version ${version}, ${list.length} files, ${(bytes / 1048576).toFixed(1)} MB`);
